// PAGE_INFO::standardPageSizes (common/page_info.cpp:42-63); every entry is landscape, `portrait` swaps.
// KiCad stores every page as a whole number of MILS, and the metric papers go through the MMsize()
// macro — EDA_UNIT_UTILS::Mm2mils = KiROUND(mm * 1000 / 25.4) (common/eda_units.cpp:72) — so A4 is
// 11693 x 8268 mils = 297.0022 x 210.0072 mm, not the nominal 297 x 210.  The difference is only
// 2-11 um, but the drawing sheet anchors to the page's right and bottom corners, so using the
// nominal value displaces every frame, tick, rule and title-block coordinate on the page and, on
// A3/A2, keeps a tick that KiCad's IsInsidePage drops (410 > 419.989 - 10).
export const MM_PER_MIL = 25.4 / 1000;
export const mm2mils = (mm: number): number => Math.round(mm * 1000 / 25.4);          // EDA_UNIT_UTILS::Mm2mils
export const milsPage = (w: number, h: number): Pt => [w * MM_PER_MIL, h * MM_PER_MIL];   // whole mils -> mm
const mmPage = (w: number, h: number): Pt => milsPage(mm2mils(w), mm2mils(h));            // MMsize()
const userMm = (mm: number): number => Math.max(mm, 10 * MM_PER_MIL);                 // clampWidth/clampHeight
export const PAPER_SIZES: Record<string, Pt> & { A4: Pt } = { A5: mmPage(210, 148), A4: mmPage(297, 210), A3: mmPage(420, 297), A2: mmPage(594, 420), A1: mmPage(841, 594), A0: mmPage(1189, 841),
  A: milsPage(11000, 8500), B: milsPage(17000, 11000), C: milsPage(22000, 17000), D: milsPage(34000, 22000), E: milsPage(44000, 34000),
  GERBER: milsPage(32000, 32000), USLetter: milsPage(11000, 8500), USLegal: milsPage(14000, 8500), USLedger: milsPage(17000, 11000) };

export function paperSize(node: SNode): Pt {
  const name = str(node[1]);
  const sizes = PAPER_SIZES;
  // A custom page keeps its mm exactly: SetWidthMM feeds SetWidthMils a *double* (include/page_info.h:136),
  // so unlike the standard papers it is not rounded to whole mils — only clamped to 10 mils
  // (common/page_info.cpp:175-190).
  let s = sizes[name] || (name === "User" ? [userMm(num(node[2], 297)), userMm(num(node[3], 210))] : PAPER_SIZES.A4);
  if (has(node, "portrait")) s = [s[1], s[0]];
  return s.slice();
}


/**
 * (title_block (title …) (date …) (rev …) (company …) (comment N "…")) — the fields
 * TITLE_BLOCK::TextVarResolver answers (common/title_block.cpp:122-190).
 */
export function titleBlockOf(node: SNode): Record<string, string> {
  const tb: Record<string, string> = {};
  for (const c of node.slice(1)) {
    if (!isList(c)) continue;
    if (c[0] === "comment") tb["comment" + num(c[1], 0)] = str(c[2]);
    else if (c[0] === "title" || c[0] === "date" || c[0] === "rev" || c[0] === "company") tb[c[0]] = str(c[1]);
  }
  return tb;
}


export function parseDoc(text: string, docType?: string): Doc {
  const tree = parse(text);
  if (!tree) throw new Error("not an s-expression document");
  if (tree[0] === "footprint" || tree[0] === "module" || docType === "footprint") {
    // a library footprint (.kicad_mod) opened in the Footprint Editor: its children are the items (footprint-doc.ts)
    if (tree[0] !== "footprint" && tree[0] !== "module") throw new Error("not a footprint");   // (module …): KiCad 5 and older
    const doc = newDoc("pcb"); doc.page = [0, 0];
    loadFootprintDoc(doc, tree, text, addItem);
    computeBBox(doc);
    return doc;
  }
  const type = tree[0] === "kicad_sch" ? "sch" : tree[0] === "kicad_pcb" ? "pcb" : (docType === "kicad_sch" ? "sch" : "pcb");
  const doc = newDoc(type);
  if (type === "sch") { const ls = kid(tree, "lib_symbols"); if (ls) for (const s of kids(ls, "symbol")) doc.lib.set(str(s[1]), s); }
  for (let j = 1; j < tree.length; j++) {
    const node = tree[j]; if (!isList(node)) continue;
    const k = node[0];
    if (k === "paper") { doc.page = paperSize(node); doc.paper = str(node[1]) || "A4"; doc.portrait = doc.page[1] > doc.page[0]; }
    else if (k === "title_block") { doc.titleBlock = titleBlockOf(node); continue; }
    else if (k === "sheet_instances") { const p = kid(node, "path"); const pg = p && kid(p, "page"); if (pg) doc.pageNumber = str(pg[1]) || "1"; continue; }
    else if (k === "version") { doc.version = num(node[1], 0); continue; }
    else if (k === "uuid") { doc.uuid = str(node[1]); continue; }   // the sheet's own id: the root of its instance paths   // echoed back on every fragment we send
    else if (type === "pcb" && k === "layers") {
      // (0 "F.Cu" signal ["user name"])
      for (const l of node.slice(1)) if (isList(l)) { const name = str(l[1]), ltype = str(l[2]); doc.layers.set(name, { id: num(l[0]), type: ltype, userName: l[3] !== undefined ? str(l[3]) : "" }); if (/\.Cu$/.test(name) && ltype !== "user") doc.copper.push(name); }
    }
    else if (k === "general") { const t = kid(node, "thickness"); if (t && type === "pcb") doc.thickness = num(t[1], 1.6); if (type === "pcb") doc.generalNode = node; continue; }   // board thickness: the 3D viewer's extrusion
    else if (k === "net") { if (type === "pcb") doc.nets.set(num(node[1], -1), str(node[2])); continue; }   // (net 3 "GND"): the board's net table
    else if (type === "pcb" && k === "setup") { const o = setupOrigins(node); doc.auxOrigin = o.aux; doc.gridOrigin = o.grid; doc.stackup = kid(node, "stackup") || null; doc.setupNode = node; continue; }   // the physical stackup is kept for impedance work   // the drill / place and grid origins
    else if (k === "embedded_files") { doc.embeddedFiles = node; continue; }   // read by the Simulation Model dialog (kicad-embed://)
    else if (k === "lib_symbols" || k === "generator" || k === "generator_version" || k === "general" || k === "setup" || k === "symbol_instances" || k === "embedded_fonts" || k === "embedded_files" || k === "uuid") continue;
    else if (type === "pcb" && PCB_KINDS.has(k) && doc.items.has(uuidOf(node))) (doc.dupItems || (doc.dupItems = [])).push({ id: uuidOf(node), node });   // a second item with an id: kept for Repair Board
    else addItem(doc, node);
  }
  computeBBox(doc);
  return doc;
}


