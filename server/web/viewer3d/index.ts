// viewer3d — KiCad's 3D Viewer for the web board editor (View → 3D Viewer, Alt+3).
//
// Built by `npm run build:viewer3d` into static/dist/viewer3d.js, a bundle of its own (three.js
// included) that the editor loads on first use (server/web/editor/viewer3d-loader.ts), so the main
// bundles do not carry WebGL code.  It registers window.KiCadViewer3D:
//
//   KiCadViewer3D.open({ getDoc, getName?, subscribe?, toast? })  → the window (focused if already open)
//   KiCadViewer3D.close() / .isOpen() / .current
//
// Package layout: outline (Edge.Cuts → board outlines, drilled holes), textures (the two faces composed
// from the document's layers with the editor's own 2D painter), bodies (placeholder component bodies),
// scene (three.js meshes of one board), viewer (renderer, camera, mouse), ui (the window: menus,
// toolbar, appearance panel, hotkeys), colors (KiCad's 3D defaults), icons.json (KiCad's icons,
// generated by server/scripts/gen_viewer3d_icons.py).
import { boardBodies, bodyStyle, footprintAttrs } from "./bodies";
import { arcPoints, assignHoles, boardHoles, boardShape, chainLoops, circlePoints, nestLoops, ovalPoints, polyArea } from "./outline";
import { stencilGeom, textureExtent } from "./textures";
import { OpenOptions, ViewerWindow } from "./ui";

let current: ViewerWindow | null = null;

export const api = {
  open(opts: OpenOptions): ViewerWindow {
    if (current && !current.closed) { current.focus(); return current; }
    current = new ViewerWindow(opts);
    return current;
  },
  close(): void { if (current) current.close(); current = null; },
  isOpen(): boolean { return !!current && !current.closed; },
  get current(): ViewerWindow | null { return current && !current.closed ? current : null; },
  /** the pure geometry behind the scene, for the node tests (static/tests/viewer3d.test.js) */
  geometry: { boardShape, boardHoles, assignHoles, chainLoops, nestLoops, arcPoints, circlePoints, ovalPoints, polyArea, boardBodies, bodyStyle, footprintAttrs, stencilGeom, textureExtent },
};

export type Viewer3DApi = typeof api;

(globalThis as unknown as { KiCadViewer3D: Viewer3DApi }).KiCadViewer3D = api;
