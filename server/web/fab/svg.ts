// web/fab/svg — SVG_PLOTTER (common/plotters/SVG_plotter.cpp): width / height in mm, a viewBox in mm with
// N decimals ("Precision" 3…6, the user unit is 10^-N mm), round caps and joins, every stroke a path.
// Text is already strokes (KiCad's stroke font), so no CSS font is involved.
import { type PlotPage, hexOf, isoDateTime } from "./plotter";

export interface SvgOptions { precision?: number; creator?: string; fileName?: string; date?: Date }

const xmlEsc = (s: string): string => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function writeSvg(page: PlotPage, o: SvgOptions = {}): string {
  const prec = Math.max(3, Math.min(6, o.precision || 4));
  const f = (v: number): string => { const s = v.toFixed(prec); return /^-0\.?0*$/.test(s) ? s.slice(1) : s; };
  const vb = page.viewBox || [0, 0, page.w, page.h];
  const out: string[] = [];
  out.push('<?xml version="1.0" standalone="no"?>', ' <!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" ', ' "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd"> ',
    "<svg", '  xmlns:svg="http://www.w3.org/2000/svg"', '  xmlns="http://www.w3.org/2000/svg"', '  xmlns:xlink="http://www.w3.org/1999/xlink"',
    '  xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"', '  version="1.1"',
    `  width="${f(vb[2])}mm" height="${f(vb[3])}mm" viewBox="${f(vb[0])} ${f(vb[1])} ${f(vb[2])} ${f(vb[3])}">`);
  out.push(`<title>SVG Image created as ${xmlEsc(o.fileName || "plot.svg")} date ${isoDateTime(o.date || new Date())} </title>`);
  out.push(`  <desc>Image generated by ${xmlEsc(o.creator || "PCBNEW")} </desc>`);
  out.push('<g style="fill:#000000; fill-opacity:1.0;stroke:#000000; stroke-opacity:1.0;', 'stroke-linecap:round; stroke-linejoin:round;"', ' transform="translate(0 0) scale(1 1)">');
  if (page.background) out.push(`<rect x="${f(vb[0])}" y="${f(vb[1])}" width="${f(vb[2])}" height="${f(vb[3])}" style="fill:${hexOf(page.background)}; stroke:none;"/>`);
  const op = (a: number | undefined, k: string): string => (a !== undefined && a < 1 ? ` ${k}-opacity:${a.toFixed(3)};` : "");
  for (const it of page.items) {
    if (it.k === "line") {
      if (it.pts.length < 2) continue;
      let d = "M" + f(it.pts[0][0]) + " " + f(it.pts[0][1]);
      for (let i = 1; i < it.pts.length; i++) d += "\nL" + f(it.pts[i][0]) + " " + f(it.pts[i][1]);
      if (it.closed) d += "\nZ";
      const cap = it.cap === "butt" || it.cap === "square" ? ` stroke-linecap:${it.cap};` : "";
      out.push(`<path style="fill:none; stroke:${hexOf(it.color)}; stroke-width:${f(it.w)};${op(it.alpha, "stroke")}${cap}"`, `d="${d}"`, "/>");
    } else if (it.k === "fill") {
      let d = "";
      for (const poly of it.polys) { if (poly.length < 3) continue; d += "M " + f(poly[0][0]) + "," + f(poly[0][1]) + "\n"; for (let i = 1; i < poly.length; i++) d += f(poly[i][0]) + "," + f(poly[i][1]) + "\n"; d += "Z "; }
      if (!d) continue;
      out.push(`<path style="fill:${hexOf(it.color)};${op(it.alpha, "fill")} stroke:none;${it.evenOdd ? " fill-rule:evenodd;" : ""}"`, `d="${d.trim()}"`, "/>");
    } else {
      const style = it.fill ? `fill:${hexOf(it.color)};${op(it.alpha, "fill")} stroke:none;` : `fill:none; stroke:${hexOf(it.color)}; stroke-width:${f(it.w)};${op(it.alpha, "stroke")}`;
      out.push(`<circle cx="${f(it.x)}" cy="${f(it.y)}" r="${f(it.r)}" style="${style}"/> `);
    }
  }
  out.push("</g> ", "</svg>", "");
  return out.join("\n");
}
