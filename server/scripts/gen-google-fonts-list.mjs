// Writes common/font/google_fonts_list.inc, the desktop app's copy of the Google Fonts list, from
// server/fonts/google-fonts.json (the list the server serves at /api/fonts/catalog).
//
//   node server/scripts/gen-google-fonts-list.mjs
//
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const list = JSON.parse(fs.readFileSync(path.join(here, '../fonts/google-fonts.json'), 'utf8'));
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const rows = list.fonts.map(([family, , , regular, bold, italics]) => `    { "${esc(family)}", ${regular}, ${bold}, ${italics} },`);
const out = `// GENERATED by server/scripts/gen-google-fonts-list.mjs from server/fonts/google-fonts.json: do not edit.
// The Google Fonts families (${list.updated}), sorted without regard to case: { family, the weight that stands
// for regular, the weight that stands for bold (0: none), bit 0: regular has an italic, bit 1: bold has one }.
// Every family is under the SIL Open Font License, the Apache License 2.0 or the Ubuntu Font Licence.
${rows.join('\n')}
`;
fs.writeFileSync(path.join(here, '../../common/font/google_fonts_list.inc'), out);
console.log(`${rows.length} families`);
