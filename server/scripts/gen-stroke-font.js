// node scripts/gen-stroke-font.js — regenerates web/canvas/newstroke-data.ts from KiCad's own stroke font
// (common/newstroke_font.cpp, the Hershey-coded glyph table STROKE_FONT::loadNewStrokeFont reads).
// Only the ranges the web canvas draws are carried: U+0020..U+052F (Latin, Greek, Cyrillic) and
// U+2000..U+23FF (punctuation, letterlike, arrows, math, technical); other code points draw as '?',
// which is what KiCad does for a glyph it does not have.
"use strict";
const fs = require("fs"), path = require("path");
const src = fs.readFileSync(path.join(__dirname, "..", "..", "common", "newstroke_font.cpp"), "utf8");
const body = src.slice(src.indexOf("newstroke_font[]"));
const re = /^\s*"((?:[^"\\]|\\.)*)"/gm; const all = []; let m;
while ((m = re.exec(body))) all.push(m[1].replace(/\\(.)/g, "$1"));
const RANGES = [[0x20, 0x52f], [0x2000, 0x23ff]];
let out = "// GENERATED by scripts/gen-stroke-font.js from common/newstroke_font.cpp — do not edit.\n" +
  "// KiCad's Newstroke font: one Hershey-coded string per glyph (first pair = left/right bearing, \" R\" = pen up).\n" +
  "export const NEWSTROKE_RANGES: ReadonlyArray<readonly [number, number, readonly string[]]> = [\n";
for (const [a, b] of RANGES) {
  const glyphs = []; for (let c = a; c <= b; c++) glyphs.push(all[c - 32] === undefined ? "" : all[c - 32]);
  out += `  [0x${a.toString(16)}, 0x${b.toString(16)}, ${JSON.stringify(glyphs)}],\n`;
}
out += "];\n";
fs.writeFileSync(path.join(__dirname, "..", "web", "canvas", "newstroke-data.ts"), out);
console.log("newstroke-data.ts:", out.length, "bytes");
