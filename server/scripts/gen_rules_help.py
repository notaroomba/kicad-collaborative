#!/usr/bin/env python3
"""Generate server/web/generated/rules-help.ts from KiCad's custom-rules help (pcbnew/dialogs/panel_setup_rules_help_*.md).

PANEL_SETUP_RULES::OnSyntaxHelp concatenates the ten markdown parts in this order and shows them in a "Syntax Help"
HTML_MESSAGE_BOX; the web converts the same markdown (editor/markdown.ts).  Run after the .md files change.
"""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
PARTS = ["1clauses", "2constraints", "3items", "4severity_names", "5examples", "6notes", "7properties", "8expression_functions", "9more_examples", "10documentation"]
text = "".join((ROOT / "pcbnew" / "dialogs" / f"panel_setup_rules_help_{p}.md").read_text(encoding="utf-8") for p in PARTS)
out = ROOT / "server" / "web" / "generated" / "rules-help.ts"
out.write_text("// GENERATED by server/scripts/gen_rules_help.py from pcbnew/dialogs/panel_setup_rules_help_*.md - do not edit.\n"
               "export const RULES_HELP_MD: string = " + json.dumps(text, ensure_ascii=False) + ";\n", encoding="utf-8")
print("wrote", out, len(text))
