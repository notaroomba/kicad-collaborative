// gen-kicursors.mjs — KiCad's canvas cursors (common/gal/cursors.cpp, resources/bitmaps_png/cursors/*.xpm) as
// CSS cursor values: each 32 px XPM becomes a PNG data URL with the hotspot cursors.cpp gives it (the non-Windows
// variants: black-on-white MOVING / WARNING / PLACE).  Writes web/editor/kicursors.generated.ts.
//   node scripts/gen-kicursors.mjs
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(here, "..", "..", "resources", "bitmaps_png", "cursors");
const OUT = path.join(here, "..", "web", "editor", "kicursors.generated.ts");

// KICURSOR -> [xpm file, hotspot] (cursors_defs, the 32 px entries)
const DEFS = {
  VOLTAGE_PROBE: ["voltage_probe.xpm", [1, 31]], CURRENT_PROBE: ["current_probe.xpm", [4, 27]], TUNE: ["cursor_tune.xpm", [1, 30]],
  PENCIL: ["cursor-pencil.xpm", [4, 27]], MOVING: ["cursor-select-m-black.xpm", [1, 1]], WARNING: ["cursor-warning-black.xpm", [1, 1]],
  REMOVE: ["cursor-eraser.xpm", [4, 4]], TEXT: ["cursor-text.xpm", [7, 7]], MEASURE: ["cursor-measure.xpm", [4, 4]],
  ADD: ["cursor-add.xpm", [7, 7]], SUBTRACT: ["cursor-subtract.xpm", [7, 7]], XOR: ["cursor-xor.xpm", [7, 7]],
  ZOOM_IN: ["cursor-zoom-in.xpm", [6, 6]], ZOOM_OUT: ["cursor-zoom-out.xpm", [6, 6]], LABEL_NET: ["cursor-label-net.xpm", [7, 7]],
  LABEL_GLOBAL: ["cursor-label-global.xpm", [7, 7]], COMPONENT: ["cursor-component.xpm", [7, 7]], SELECT_LASSO: ["cursor-select-lasso.xpm", [7, 7]],
  SELECT_WINDOW: ["cursor-select-window.xpm", [7, 10]], LINE_BUS: ["cursor-line-bus.xpm", [5, 26]], LINE_WIRE: ["cursor-line-wire.xpm", [5, 26]],
  LINE_GRAPHIC: ["cursor-line-graphic.xpm", [5, 26]], LABEL_HIER: ["cursor-label-hier.xpm", [7, 7]], PLACE: ["cursor-place-black.xpm", [1, 1]],
};

function parseXpm(text) {
  const strs = [...text.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => m[1]);
  const [w, h, n, cpp] = strs[0].trim().split(/\s+/).map(Number);
  const colors = new Map();
  for (let i = 1; i <= n; i++) { const s = strs[i]; const key = s.slice(0, cpp); const c = /c\s+(\S+)/.exec(s.slice(cpp))[1]; colors.set(key, c); }
  const px = Buffer.alloc(w * h * 4);
  for (let y = 0; y < h; y++) { const row = strs[1 + n + y]; for (let x = 0; x < w; x++) {
    const c = colors.get(row.slice(x * cpp, x * cpp + cpp)) || "None", o = (y * w + x) * 4;
    if (/^none$/i.test(c)) continue;
    const hex = c.replace("#", ""); px[o] = parseInt(hex.slice(0, 2), 16); px[o + 1] = parseInt(hex.slice(2, 4), 16); px[o + 2] = parseInt(hex.slice(4, 6), 16); px[o + 3] = 255;
  } }
  return { w, h, px };
}
const CRC = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; return c; });
const crc32 = (b) => { let c = -1; for (const x of b) c = CRC[(c ^ x) & 255] ^ (c >>> 8); return (c ^ -1) >>> 0; };
function chunk(type, data) { const l = Buffer.alloc(4); l.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc32(td)); return Buffer.concat([l, td, c]); }
function png({ w, h, px }) {
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6;
  const raw = Buffer.alloc((w * 4 + 1) * h); for (let y = 0; y < h; y++) px.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4);
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]), chunk("IHDR", ihdr), chunk("IDAT", zlib.deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}

let out = "// kicursors.generated.ts — GENERATED by scripts/gen-kicursors.mjs from resources/bitmaps_png/cursors (KiCad's\n// common/gal/cursors.cpp cursors_defs, 32 px, non-Windows variants).  Do not edit.\n\n";
out += "/** KICURSOR name -> [PNG data URL, hotspot x, hotspot y] */\nexport const KICURSOR_IMAGES: Record<string, [string, number, number]> = {\n";
for (const [name, [file, hot]] of Object.entries(DEFS)) {
  const img = parseXpm(fs.readFileSync(path.join(SRC, file), "utf8"));
  out += `  ${name}: ["data:image/png;base64,${png(img).toString("base64")}", ${hot[0]}, ${hot[1]}],\n`;
}
out += "};\n";
fs.writeFileSync(OUT, out);
console.log("wrote", OUT, out.length, "bytes");
